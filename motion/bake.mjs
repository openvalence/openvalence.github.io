// bake.mjs -- runs the real Kinetic² planner (kinetic2.wasm) over the knots the
// Screen to rail shows and writes kinetic-data.js: the curve on the planner's 1 ms grid.
// Usage: node bake.mjs [path/to/kinetic2.wasm]   (default: the deployed playground build)
// Constraints: layouts are the ABI structs in Kinetic wasm/kinetic2_wasm.h.
import { readFile, writeFile } from 'node:fs/promises';

const src = process.argv[2];
const bytes = src ? await readFile(src) : Buffer.from(await (await fetch('https://openvalence.org/Kinetic/kinetic2.wasm')).arrayBuffer());
const { instance } = await WebAssembly.instantiate(bytes, {});
const K = instance.exports;
K._initialize();
const h = K.kinetic2_create();
const dv = () => new DataView(K.memory.buffer);
const sBuf = K.malloc(24), kBuf = K.malloc(40);
const cstr = (p) => { const m = new Uint8Array(K.memory.buffer); let s = ''; for (let i = p; m[i]; i++) s += String.fromCharCode(m[i]); return s; };

// Playground defaults (Kinetic playground/play.js DEF): window units.
const CFG = { vmax: 3, amax: 30, jmax: 2000, smooth: 0, floor: 0.15, trim: 1, react: 4 };

// Knots authored ahead, as the playground's 'ahead' mode submits them: all at t = 0.
function plan(p0, knots, T) {
  K.kinetic2_configure(h, CFG.vmax, CFG.amax, CFG.jmax, CFG.smooth, CFG.floor, CFG.trim, CFG.react * 1000);
  K.kinetic2_reset(h, p0, 0);
  for (const [t, p, v] of knots) {
    const ok = K.kinetic2_submit(h, Math.round(t * 1e6), p, v == null ? 0 : 1, v ?? 0, 0, v == null ? 0x2 : 0);
    if (!ok) throw new Error('knot refused at ' + t);
  }
  const solved = [];
  K.kinetic2_solved(h, 0, kBuf);
  for (let i = 0, n = K.kinetic2_pending(h); i < n; i++) {
    K.kinetic2_solved(h, i, kBuf);
    const d = dv();
    solved.push({ t: d.getFloat64(kBuf, true) / 1e6, p: d.getFloat32(kBuf + 8, true), share: +d.getFloat32(kBuf + 20, true).toFixed(3) });
  }
  const n = Math.round(T * 1000) + 1, P = [];
  for (let i = 0; i < n; i++) {
    K.kinetic2_sample(h, i * 1000, sBuf);
    const d = dv();
    P.push(+d.getFloat32(sBuf + 8, true).toFixed(4));
  }
  return { p0, knots: knots.map(([t, p]) => [t, p]), solved, P };
}

const data = {
  version: cstr(K.kinetic2_version()),
  config: CFG,
  // Screen to rail: one 4 s script, at rest at both ends so three repeats loop clean.
  stroke: plan(0.2, [[0.5, 0.8], [1.0, 0.3], [1.4, 0.9], [1.9, 0.25], [2.3, 0.7], [2.7, 0.35], [3.3, 0.85], [3.8, 0.2, 0]], 4),
};
await writeFile(new URL('./kinetic-data.js', import.meta.url), '// Generated by bake.mjs from ' + data.version + '. Do not edit.\nwindow.KDATA = ' + JSON.stringify(data) + ';\n');
console.log(data.version, 'stroke solved:', JSON.stringify(data.stroke.solved));
